"""look-check: writes looks.h, pages.c and mod.json from a dump of a stock 1.74 boot's RAM 0x419a4000..0x419ae800
(the UI records, 84 bytes an id from 0x419a4888; README). Run in this folder: python3 gen_looks.py DUMP.bin"""
import struct,collections,sys,json
d=open(sys.argv[1],'rb').read(); B=0x419a4000; R=0x419a4888
recs=[struct.unpack('>21I',d[R-B+84*i:R-B+84*i+84]) for i in range(469)]
def f(r,o): k=o//4; return (r[k+2],r[k+3])
def key(r): return (r[0],)+r[1:5]+tuple(f(r,o) for o in (0x14,0x24,0x34,0x44))
g=collections.OrderedDict()
for i,r in enumerate(recs): g.setdefault(key(r),[]).append(i)
reps=[ids[0] if ids[0] else ids[1] for ids in g.values() if ids != [0]]
gr=collections.OrderedDict()
for i,r in enumerate(recs): gr.setdefault(f(r,0x24),[]).append(i)
print(len(reps),'records',len(gr),'graphics')
n=len(reps)
h=['/* generated by the look-check README\'s script from the UI records of a stock 1.74 boot',
   ' * (0x419a4888, 84 bytes an id): one stock id for each different record, its flags, turn',
   ' * steps and four delegates (%d of 469; %d different graphics). */' % (n, len(gr)),
   '#define NLOOK %d' % n,
   '#define LOOK_IDS ' + ', '.join(map(str,reps)),
   '#define UI_LOOK 457                     /* the ui pair: a copy of CB TEST\'s switch */',
   '#define LOOK_ENTRIES ' + ', '.join('{CORE_KNOB(%d), CORE_KNOB(%d), %d, 0, 0, 0}'%(k,k,L) for k,L in enumerate(reps))]
open('looks.h','w').write('\n'.join(h)+'\n')
nown=n+2; pages=(nown+3)//4
def contrib(to,sym,order=50): return {"to":to,"order":order,"data":"00000000","relocs":[[0,"abs32","sym:"+sym,0]]}
c=[contrib('core_params','lk_params_own'),contrib('core_params','lk_params_stock'),contrib('core_param_locks','lk_locks')]
for p in range(pages):
    c.append(contrib('core_pages','lk_page_%d'%p))
    c.append(contrib('core_view_pages','lk_view_%d'%p,30+p))
for k in range(n):
    c.append({"to":"core_knob_looks","order":50,"data":"00000000","relocs":[[0,"abs32","sym:lk_looks_each",24*k]]})
c.append(contrib('core_knob_looks','lk_look_ui')); c.append(contrib('core_knob_looks','lk_look_range'))
m={"id":"look-check","version":"0.1","title":"Look check","category":"Examples","license":"GPL-2.0-or-later","author":"Iced-Cream",
 "description":"A test for core-ar2 0.13's knob looks (core_knob_looks). LOOK CHECK pages, %d of them (the first 12 behind the LFO key, the rest behind AMP), four pairs of knobs a page: a stock id on A, C, E and G and on B, D, F and H a knob id of the mod's own that takes that id's look, for one stock id of each of the %d different UI records of 1.74; both knobs of a pair show the same value, text, label and name, so the two cells of a pair are the same pixel for pixel when core gives the look. The last page's own knobs take a UI record from a ui callback (a copy of CB TEST's) and COMP MIX's look with a range of 0..12. After the magic LKC1, what core's UI record and range lookups answer for every own knob." % (pages, n),
 "device":"analog-rytm-mk2","os":"1.74","knobs":nown,"resources":{"core":"0.13"},"requires":["core"],
 "sources":["look.c","pages.c"],
 "subscribe":[{"event":"ev_tick","fn":"lk_tick","order":60}],
 "contribute":c}
json.dump(m,open('mod.json','w'),indent=1); open('mod.json','a').write('\n')
pc=['/* SPDX-License-Identifier: GPL-2.0-or-later */','/* look-check: its pages (generated with looks.h) */','#include <stdint.h>','#include "analog-rytm-mk2/pages.h"','#include "looks.h"','CORE_KNOBS;','static const int16_t l[] = {LOOK_IDS, UI_LOOK, 94};']
for p in range(pages):
    ids=[]
    for j in range(4):
        k=4*p+j
        ids += ['l[%d]'%k,'CORE_KNOB(%d)'%k] if k<nown else ['0','0']
    pc.append('const struct core_page lk_page_%d = {%d, "LOOK CHECK %d", {%s}};'%(p,60+p,p+1,', '.join(ids)))
    pc.append('const struct core_view_page lk_view_%d = {%s, %d, 0};'%(p,'CORE_VIEW_LFO' if p<12 else 'CORE_VIEW_AMP',60+p))
open('pages.c','w').write('\n'.join(pc)+'\n')
print(pages,'pages', reps)
